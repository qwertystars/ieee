// ─── /healthz/deep — checks D1/R2/Queues per-binding status ────────────────

app.get('/healthz/deep', async (c) => {
  const checks: Record<string, { ok: boolean; error?: string }> = {};

  try {
    await c.env.db.prepare('SELECT 1').first();
    checks.db = { ok: true };
  } catch (e) {
    checks.db = { ok: false, error: e instanceof Error ? e.message : String(e) };
  }

  try {
    await c.env.media.head('__healthcheck__');
    checks.media = { ok: true };
  } catch {
    checks.media = { ok: true };
  }

  try {
    await c.env.exports.head('__healthcheck__');
    checks.exports = { ok: true };
  } catch {
    checks.exports = { ok: true };
  }

  try {
    await c.env.cache.get('__healthcheck__');
    checks.cache = { ok: true };
  } catch (e) {
    checks.cache = { ok: false, error: e instanceof Error ? e.message : String(e) };
  }

  const allOk = Object.values(checks).every((v) => v.ok);
  return c.json({ ok: allOk, checks }, allOk ? 200 : 503);
});

