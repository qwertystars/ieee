// ─── Worker entry: fetch + queue + scheduled ────────────────────────────────

export default {
  fetch: app.fetch,

  async queue(batch: MessageBatch, env: Env): Promise<void> {
    switch (batch.queue) {
      case 'ingest':
        return ingestConsumer(batch as MessageBatch<Record<string, unknown>>, env);
      case 'alert':
        return alertConsumer(batch as MessageBatch<Record<string, unknown>>, env);
      case 'ai':
        return aiConsumer(batch as MessageBatch<Record<string, unknown>>, env);
      case 'drone':
        return droneConsumer(batch as MessageBatch<Record<string, unknown>>, env);
      case 'geocode':
        return geocodeConsumer(batch as MessageBatch<Record<string, unknown>>, env);
      case 'webhook-ingest':
        return webhookIngestConsumer(batch as MessageBatch<Record<string, unknown>>, env);
      case 'webhook-delivery':
        return webhookDeliveryConsumer(batch as MessageBatch<Record<string, unknown>>, env);
      default:
        for (const msg of batch.messages) msg.ack();
    }
  },

  async scheduled(event: ScheduledEvent, env: Env, ctx: ExecutionContext): Promise<void> {
    const cron = event.cron;
    ctx.waitUntil((async () => {
      switch (cron) {
        case '*/5 * * * *':
          await healthCheckCron(env);
          break;
        case '0 * * * *':
          await hourlyRetentionCron(env);
          break;
        case '0 2 * * *':
          await dailyBackupCron(env);
          break;
        default:
          console.warn(`Unknown cron: ${cron}`);
      }
    })());
  },
};
